#!/usr/bin/env python3
"""Generate SCENE_SWITCHES.md: a migration worklist for the household's
battery Zigbee scene switches (Tuya category "wxkg", 1/2/4-button models --
see MIGRATION.md's switch-mapping section).

Reads the newest tuya_export_*.json (cloud export -- these are Zigbee
sub-devices, no local_key/LAN component to poll, cloud data is all there
is). No secrets in the output (sub-devices have no local_key), safe to
commit in this repo.

Button count comes from devices.spec (product-defined), not live status --
status only shows buttons that have actually been pressed at least once
since the last sync, which under-reports on a freshly-synced export.
"""
import json
import re
from pathlib import Path

EXPORT_DIR = Path(__file__).parent / "tuya_export"

files = sorted(EXPORT_DIR.glob("tuya_export_*.json"))
if not files:
    raise FileNotFoundError(f"No tuya_export_*.json in {EXPORT_DIR}. Run export.ipynb first.")
data = json.load(open(files[-1], encoding="utf-8"))
print(f"Using {files[-1].name}")

detail = data["devices"]["detail"]
status = data["devices"]["status"]
spec = data["devices"]["spec"]

switches = [(did, dd) for did, dd in detail.items() if dd.get("category") == "wxkg"]
switches.sort(key=lambda kv: kv[1].get("name", ""))

BUTTON_RE = re.compile(r"(switch_mode\d+)")

lines = []
lines.append("# Zigbee scene-switch migration worklist\n")
lines.append(
    "Generated by `scene_switches_worklist.py` from the Tuya cloud export. "
    "See `MIGRATION.md`'s switch-mapping section for the full writeup -- "
    "short version: these report per-button gesture (`click`/`double_click`/"
    "`press`) as a DP today, and are very likely Tesla-Smart rebrands of the "
    "well-supported Zigbee2MQTT/ZHA `TS0041`/`TS0042`/`TS0044` scene "
    "switches (1/2/4-button), confirmed by Tesla's documented `TSL-SEN-BUTTON`"
    " = `TS0041` rebrand precedent. Not yet verified by actually pairing one "
    "to HA's coordinator.\n"
)
lines.append(
    "**Before re-pairing any of these to HA's own Zigbee coordinator, "
    "open each switch's settings screen in the SmartLife/Tuya app and "
    "record what every button+gesture currently triggers.** The cloud "
    "export's `scene_bindings` came back empty for all 10 of these -- that "
    "mapping is stored locally by the Zigbee gateway, not the cloud API, "
    "and is **not recoverable after the fact** once a switch is removed "
    "from Tuya.\n"
)

for did, dd in switches:
    name = dd.get("name", "?")
    model = dd.get("model") or "(no model string)"
    product_id = dd.get("product_id", "?")
    online = dd.get("online")
    st = {s["code"]: s["value"] for s in status.get(did, [])}
    sp = spec.get(did, {})
    spec_codes = [f["code"] for f in (sp.get("status") or [])]
    buttons = sorted(
        set(m.group(1) for c in spec_codes if (m := BUTTON_RE.match(c))),
        key=lambda b: int(b.replace("switch_mode", "")),
    )

    lines.append(f"## {name}\n")
    lines.append(f"- model: `{model}` (product_id `{product_id}`)")
    lines.append(f"- buttons: {len(buttons)}")
    lines.append(f"- online: {online}")
    if "battery_percentage" in st:
        lines.append(f"- battery: {st['battery_percentage']}%")
    if "mode" in st:
        explainer = (
            "button presses are DP-readable"
            if st["mode"] == "remote_control"
            else "gateway likely consumes presses locally via scene-binding -- "
            "switch to remote_control to make them DP-readable instead"
        )
        lines.append(f"- mode: `{st['mode']}` ({explainer})")
    lines.append("")
    lines.append(
        "| button | last reported gesture (Tuya) | currently triggers (fill in from app) | desired HA action |"
    )
    lines.append("|---|---|---|---|")
    for b in buttons:
        num = b.replace("switch_mode", "")
        last = st.get(b, "(never pressed since last sync)")
        lines.append(f"| {num} | `{last}` | | |")
    lines.append("")

out_path = Path(__file__).parent / "tuya_export" / "ha" / "SCENE_SWITCHES.md"
out_path.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {out_path} ({len(switches)} switches)")
